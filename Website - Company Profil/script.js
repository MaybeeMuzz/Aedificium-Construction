/* =========================
   LANGUAGE SYSTEM
========================= */
function setLanguage(lang) {
    document.querySelectorAll("[data-lang]").forEach(el => {
        const key = el.getAttribute("data-lang");
        const val = translations[lang]?.[key];
        if (val !== undefined) el.innerHTML = val;
    });

    // Update ALL lang buttons (navbar + drawer)
    document.querySelectorAll("[data-lang-code]").forEach(btn => {
        btn.classList.toggle("active", btn.dataset.langCode === lang);
    });

    localStorage.setItem("lang", lang);
}

// Attach to all lang buttons via event delegation
document.addEventListener("click", e => {
    const btn = e.target.closest("[data-lang-code]");
    if (btn) setLanguage(btn.dataset.langCode);
});

// Init
setLanguage(localStorage.getItem("lang") || "id");


